export function inhabitantJobs(entry) {
  const same = entry.m === entry.f
  if (same) return [{ label: entry.m, gender: 'person', slug: entry.m }]
  return [
    { label: entry.m, gender: 'man', slug: entry.m },
    { label: entry.f, gender: 'woman', slug: entry.f },
  ]
}

export function promptFor(entry, job) {
  const genderWord =
    job.gender === 'man' ? 'adult man' : job.gender === 'woman' ? 'adult woman' : 'adult person'
  return (
    `Photorealistic studio photo of one ${entry.look} ${genderWord}, standing centered, ` +
    `holding a small handheld ${entry.flag} clearly visible in one hand, ` +
    `casual modern everyday clothes, respectful natural look, no costume caricature, ` +
    `plain pure white background (#FFFFFF), no shadows on the floor, no props except the flag, ` +
    `no text, no watermark, no logo, 4:3 product-style photo`
  )
}
